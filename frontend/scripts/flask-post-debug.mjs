import { chromium } from 'playwright';
const browser=await chromium.launch({headless:true});
const context=await browser.newContext({viewport:{width:1440,height:900}});
const page=await context.newPage();
await page.goto('http://127.0.0.1:5000/login');
const resp=await page.evaluate(async()=>{const fd=new FormData();fd.append('username','owner');fd.append('password','Owner@12345'); const r=await fetch('/login',{method:'POST',body:fd,redirect:'follow'}); return {status:r.status,url:r.url,text:(await r.text()).slice(0,200)};});
console.log(resp);
await page.goto('http://127.0.0.1:5000/sales',{waitUntil:'networkidle'});
await page.waitForTimeout(1000);
console.log('url',page.url());
console.log((await page.locator('body').innerText()).slice(0,300));
await page.screenshot({path:'D:/System/car_showroom_management/delivery/flask-sales-debug.png'});
await browser.close();
