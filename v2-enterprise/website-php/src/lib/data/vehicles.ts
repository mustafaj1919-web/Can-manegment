export function getRelatedVehicles(vehicle: Vehicle, count = 3) {
  return VEHICLES.filter((v) => v.id !== vehicle.id && v.category === vehicle.category)
    .concat(VEHICLES.filter((v) => v.id !== vehicle.id && v.category !== vehicle.category))
    .slice(0, count);
}
